#!/bin/sh
# The language server's test: gcon lsp is its own oracle. Sessions are
# made by tests/lspsession.c: basic (initialize, open a file, document
# symbols in both forms, formatting, shutdown) and features (also hover,
# definition, references, highlights, signature help, completion,
# prepare rename and rename at every STEPth identifier, then workspace
# symbols).
#
#   - Golden: features sessions on probes in the repository (listed
#     below, each with its STEP; completion at every fifth position),
#     whose replies are recorded in src/tests/lsp/PATH.golden (the
#     repository's path written as ROOT); src/tests/lsp/docs.icn with
#     the reference-page fixtures in src/tests/lsp/ref.
#   - For every .icn file of the corpus (the Icon tree beside the
#     checkout, gcon's library and tests, ../icn): a basic session, and
#     for every tenth file a features session (FULL=1: every file, and
#     basic sessions in both symbol forms), must get a reply to every
#     request, with nothing on standard error and exit status 0.
#   - gcon's literals: the diagnostics for the probes in src/tests/lit
#     must be the errors gcon build reports.
#
#   src/tests/lsp.sh            check
#   src/tests/lsp.sh -update    rewrite the golden files
#
# JOBS workers share the corpus (default: one per CPU); SANITIZE=1
# builds gcon with the address and undefined-behaviour sanitizers.
set -u
# gcon exits without freeing what it built, as icont does: no leak checks
# (ASan makes them on Linux, by default)
export ASAN_OPTIONS=detect_leaks=0${ASAN_OPTIONS:+:$ASAN_OPTIONS}
here=$(cd "$(dirname "$0")/../.." && pwd)
gold=$here/src/tests/lsp
update=
[ "${1:-}" = -update ] && update=1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
CC=${CC:-cc}
if [ "${SANITIZE:-}" = 1 ]; then
	flags="-g -O1 -fsanitize=address,undefined -fno-sanitize-recover=all"
else
	flags="-O2"
fi
$CC -std=c11 $flags -DGCON_VERSION='"test"' -I"$here/vm/src" -o "$tmp/gcon" "$here"/src/*.c \
	"$here/vm/src/gen_tables.c" || exit 2
$CC -std=c11 -O1 -I"$here/vm/src" -o "$tmp/lspsession" "$here/src/tests/lspsession.c" "$here/src/json.c" \
	"$here/src/util.c" "$here/src/token.c" "$here/src/lexer.c" || exit 2
# lib/gcon/uclass.icn is generated by build.sh; programs link it
[ -f "$here/lib/gcon/uclass.icn" ] || sh "$here/tools/uclass.sh" >/dev/null || exit 2
GCONROOT=$here
LC_ALL=C
export GCONROOT LC_ALL
unset IPATH LPATH
mkdir "$tmp/nodocs"
fail=0

# Golden sessions: FILE STEP [DOCS].
gn=0 gfail=0
while read -r rel step docs; do
	gn=$((gn + 1))
	d=$tmp/nodocs
	[ -n "$docs" ] && d=$here/$docs
	LSPCOMPLETE=5 "$tmp/lspsession" features "$here/$rel" "$step" >"$tmp/g.sess"
	"$tmp/gcon" lsp -docs "$d" <"$tmp/g.sess" 2>&1 | "$tmp/lspsession" split |
		sed "s|$here|ROOT|g" >"$tmp/g.out"
	want=$gold/$rel.golden
	if [ "$update" ]; then
		mkdir -p "$(dirname "$want")"
		cp "$tmp/g.out" "$want"
	elif ! cmp -s "$want" "$tmp/g.out"; then
		gfail=$((gfail + 1))
		echo "GOLDEN $rel"
		diff "$want" "$tmp/g.out" | cut -c1-300 | head -6
	fi
done <<'EOF'
src/tests/lsp/docs.icn 1 src/tests/lsp/ref
src/tests/lit/literals.icn 3
src/tests/sema/builtins.icn 4
src/tests/sema/keywords.icn 3
src/tests/sema/redecl.icn 3
src/tests/sema/reach.icn 4
src/tests/sema/link2/a.icn 2
vm/tests/programs/link.icn 2
src/tests/vet/selflink.icn 3
EOF
if [ "$update" ]; then
	echo "lsp: $gn golden sessions rewritten"
else
	echo "lsp: $gn golden sessions, $gfail differ"
fi
fail=$((fail + gfail))

# The corpus.
{
	[ -d "$here/../icon" ] && find "$here/../icon" -name '*.icn' -not -path '*/.git/*'
	find "$here/lib" "$here/experiments" "$here/vm/tests" "$here/src/tests" -name '*.icn'
	[ -d "$here/../icn" ] && find "$here/../icn" -name '*.icn'
} | sort >"$tmp/list"

# check SESSION: run it, writing "ok N" (N requests answered) or a problem.
check() {
	"$tmp/gcon" lsp -docs "$tmp/nodocs" <"$1" 2>"$w.err" | "$tmp/lspsession" split >"$w.out"
	s=$?
	want=$(grep -o '"jsonrpc":"2.0","id":' "$1" | wc -l | tr -d ' ')
	got=$(grep -c '^{"jsonrpc":"2.0","id":' "$w.out")
	if [ "$s" != 0 ] || [ -s "$w.err" ] || [ "$want" != "$got" ]; then
		echo "PROBLEM $f ($2): status $s, $got of $want requests answered, $(head -1 "$w.err")"
	else
		echo "ok $got"
	fi
}

# work LIST OUT: run the sessions for LIST's files, results to OUT.
work() {
	w=$2.tmp
	n=0
	while read -r f; do
		n=$((n + 1))
		"$tmp/lspsession" basic "$f" 1 >"$w.sess" || continue
		check "$w.sess" basic
		if [ "${FULL:-}" = 1 ]; then
			"$tmp/lspsession" basic "$f" 0 >"$w.sess" && check "$w.sess" "basic, flat symbols"
		fi
		if [ "${FULL:-}" = 1 ] || [ $((n % 10)) = 0 ]; then
			"$tmp/lspsession" features "$f" "${STEP:-7}" >"$w.sess" && check "$w.sess" features
		fi
	done <"$1" >"$2"
}
jobs=${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}
awk -v n="$jobs" -v d="$tmp" '{ print > (d "/part" (NR % n)) }' "$tmp/list"
for part in "$tmp"/part*; do
	work "$part" "$part.res" &
done
wait
cat "$tmp"/part*.res >"$tmp/results"
grep '^PROBLEM' "$tmp/results"
problems=$(grep -c '^PROBLEM' "$tmp/results")
echo "lsp: $(grep -c '^ok' "$tmp/results") corpus sessions," \
	"$(awk '/^ok / { n += $2 } END { print n + 0 }' "$tmp/results") requests answered; $problems problems"
fail=$((fail + problems))

# gcon's literals: the diagnostics are gcon build's errors.
lfail=0
for f in "$here"/src/tests/lit/*.icn; do
	(cd "$(dirname "$f")" && "$tmp/gcon" build -o /dev/null "$(basename "$f")") 2>&1 |
		sed 's/^File [^;]*; Line //' >"$tmp/lit.build"
	"$tmp/lspsession" basic "$f" 1 | "$tmp/gcon" lsp 2>/dev/null | "$tmp/lspsession" diags >"$tmp/lit.lsp"
	if ! cmp -s "$tmp/lit.build" "$tmp/lit.lsp"; then
		echo "DIFF $f (diagnostics and gcon build)"
		diff "$tmp/lit.build" "$tmp/lit.lsp"
		lfail=$((lfail + 1))
	fi
done
echo "lsp: $(ls "$here"/src/tests/lit/*.icn | wc -l | tr -d ' ') literal probes, $lfail differ from gcon build"
fail=$((fail + lfail))
# Linked files are found in the linking file's directory, then in the
# workspace folders (gcon help library): a file in sub/ links lib, which
# is only in the workspace's top directory; definition must reach it,
# with the folder named by workspaceFolders and by rootUri, and must not
# without one.
ws=$tmp/ws
mkdir -p "$ws/sub"
printf 'procedure helper()\n   return 1\nend\n' >"$ws/lib.icn"
printf 'link lib\n\nprocedure main()\n   helper()\nend\n' >"$ws/sub/main.icn"
# frame JSON: the message with its header.
frame() { printf 'Content-Length: %d\r\n\r\n%s' "$(printf '%s' "$1" | wc -c | tr -d ' ')" "$1"; }
# session INIT: the reply to definition at helper() in sub/main.icn.
session() {
	text=$(awk '{ gsub(/"/, "\\\""); printf "%s\\n", $0 }' "$ws/sub/main.icn")
	{
		frame "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",\"params\":{\"processId\":null,$1,\"capabilities\":{}}}"
		frame '{"jsonrpc":"2.0","method":"initialized","params":{}}'
		frame "{\"jsonrpc\":\"2.0\",\"method\":\"textDocument/didOpen\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/sub/main.icn\",\"languageId\":\"icon\",\"version\":1,\"text\":\"$text\"}}}"
		frame "{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"textDocument/definition\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/sub/main.icn\"},\"position\":{\"line\":3,\"character\":4}}}"
		frame '{"jsonrpc":"2.0","id":3,"method":"shutdown"}'
		frame '{"jsonrpc":"2.0","method":"exit"}'
	} | (cd / && "$tmp/gcon" lsp 2>/dev/null) | "$tmp/lspsession" split | grep '"id":2,'
}
wfail=0
for init in "\"workspaceFolders\":[{\"uri\":\"file://$ws\",\"name\":\"ws\"}],\"rootUri\":null" "\"rootUri\":\"file://$ws\""; do
	session "$init" | grep -q "file://$ws/lib.icn" || {
		echo "FAIL link lookup: lib.icn not found through the workspace ($init)"
		wfail=$((wfail + 1))
	}
done
session '"rootUri":null' | grep -q 'lib.icn' && {
	echo "FAIL link lookup: lib.icn found with no workspace folder"
	wfail=$((wfail + 1))
}
echo "lsp: link lookup through workspace folders, $wfail problems"
# Hover on a built-in with a reference entry (doc/ref) shows the entry.
printf 'procedure main()\n   find("a", "b")\nend\n' >"$ws/hover.icn"
text=$(awk '{ gsub(/"/, "\\\""); printf "%s\\n", $0 }' "$ws/hover.icn")
{
	frame '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"processId":null,"rootUri":null,"capabilities":{}}}'
	frame '{"jsonrpc":"2.0","method":"initialized","params":{}}'
	frame "{\"jsonrpc\":\"2.0\",\"method\":\"textDocument/didOpen\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/hover.icn\",\"languageId\":\"icon\",\"version\":1,\"text\":\"$text\"}}}"
	frame "{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"textDocument/hover\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/hover.icn\"},\"position\":{\"line\":1,\"character\":4}}}"
	frame '{"jsonrpc":"2.0","id":3,"method":"shutdown"}'
	frame '{"jsonrpc":"2.0","method":"exit"}'
} | GCONROOT=$here "$tmp/gcon" lsp 2>/dev/null | "$tmp/lspsession" split | grep '"id":2,' >"$tmp/hover"
hfail=0
grep -q 'Generates the positions' "$tmp/hover" && grep -q 'gcon doc find' "$tmp/hover" || {
	echo "FAIL hover on find: not its reference entry"
	head -c 400 "$tmp/hover"
	hfail=1
}
echo "lsp: hover from the reference, $hfail problems"
# Hover on a procedure of Gcon's own library (lib/gcon) shows its entry.
printf 'link uclass\n\nprocedure main()\n   uclass("L")\nend\n' >"$ws/hover2.icn"
text=$(awk '{ gsub(/"/, "\\\""); printf "%s\\n", $0 }' "$ws/hover2.icn")
{
	frame '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"processId":null,"rootUri":null,"capabilities":{}}}'
	frame '{"jsonrpc":"2.0","method":"initialized","params":{}}'
	frame "{\"jsonrpc\":\"2.0\",\"method\":\"textDocument/didOpen\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/hover2.icn\",\"languageId\":\"icon\",\"version\":1,\"text\":\"$text\"}}}"
	frame "{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"textDocument/hover\",\"params\":{\"textDocument\":{\"uri\":\"file://$ws/hover2.icn\"},\"position\":{\"line\":3,\"character\":5}}}"
	frame '{"jsonrpc":"2.0","id":3,"method":"shutdown"}'
	frame '{"jsonrpc":"2.0","method":"exit"}'
} | GCONROOT=$here "$tmp/gcon" lsp 2>/dev/null | "$tmp/lspsession" split | grep '"id":2,' >"$tmp/hover2"
grep -q 'general category or script' "$tmp/hover2" && grep -q 'gcon doc uclass' "$tmp/hover2" || {
	echo "FAIL hover on uclass: not its reference entry"
	head -c 400 "$tmp/hover2"
	fail=$((fail + 1))
}
fail=$((fail + hfail))
fail=$((fail + wfail))
[ $fail -eq 0 ]
