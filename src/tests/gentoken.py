#!/usr/bin/env python3
# Writes src/tokens.inc, the C front end's token kinds and their
# spellings and flags, from the Go reference's internal/token/token.go
# (whose tables are icont's lextab.h, and checked against it). Run from
# the repository root; needed only while the Go is the reference.
import re
src = open('internal/token/token.go').read()
body = src[src.index('ILLEGAL Kind = iota'):]
body = body[:body.index('\n)')]
names = [l.split()[0] for l in body.split('\n') if l.split() and not l.split()[0].startswith('//')]
infos = {m[0]: (m[1], m[2]) for m in re.findall(r'^\t(\w+):\s*\{("(?:[^"\\]|\\.)*"), ([^}]*)\},', src, re.M)}
enum = ['\tT_%s,' % n for n in names]
tab = []
for n in names:
    if n in infos:
        spell, flags = infos[n]
        fl = flags.replace('Beginner', 'TF_BEGINNER').replace('Ender', 'TF_ENDER').strip()
        tab.append('\t[T_%s] = {%s, %s},' % (n, spell, fl))
with open('src/tokens.inc', 'w') as f:
    f.write('/* Generated by src/tests/gentoken.py from the Go reference\'s\n'
            ' * internal/token/token.go, whose tables are icont\'s lextab.h. */\n\n')
    f.write('enum TokKind {\n' + '\n'.join(enum) + '\n\tT_NKINDS\n};\n\n')
    f.write('#ifdef TOKEN_TABLE\nstatic const struct TokInfo tokinfo[T_NKINDS] = {\n' + '\n'.join(tab) + '\n};\n#endif\n')
print(len(names), 'kinds,', len(tab), 'with spellings')
