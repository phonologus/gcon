#!/bin/sh
# Writes src/tokens.inc, the C front end's token kinds and their
# spellings and flags, from the Go reference's internal/token/token.go
# (whose tables are icont's lextab.h, and checked against it). Run from
# the repository root; needed only while the Go is the reference.
set -eu
awk '
# golit: the Go string literal at the start of s (with its quotes)
function golit(s,   i, c) {
	for (i = 2; i <= length(s); i++) {
		c = substr(s, i, 1)
		if (c == "\\") i++
		else if (c == "\"") return substr(s, 1, i)
	}
	return s
}
/ILLEGAL Kind = iota/ { inkinds = 1 }
inkinds && /^\)/ { inkinds = 0 }
inkinds {
	line = $0
	sub(/^[ \t]+/, "", line)
	if (line == "" || line ~ /^\/\//) next
	split(line, w, /[ \t]+/)
	names[++n] = w[1]
	next
}
/^\t[A-Za-z_][A-Za-z_0-9]*:[ \t]*\{"/ {
	name = $0
	sub(/^\t/, "", name)
	sub(/:.*/, "", name)
	rest = substr($0, index($0, "{\"") + 1)
	spell = golit(rest)
	rest = substr(rest, length(spell) + 1)
	sub(/^, /, "", rest)
	flags = substr(rest, 1, index(rest, "}") - 1)
	gsub(/Beginner/, "TF_BEGINNER", flags)
	gsub(/Ender/, "TF_ENDER", flags)
	sub(/^[ \t]+/, "", flags)
	sub(/[ \t]+$/, "", flags)
	spelling[name] = spell
	flag[name] = flags
}
END {
	print "/* Generated by src/tests/gentoken.sh from the Go reference'"'"'s"
	print " * internal/token/token.go, whose tables are icont'"'"'s lextab.h. */"
	print ""
	print "enum TokKind {"
	for (i = 1; i <= n; i++) printf "\tT_%s,\n", names[i]
	print "\tT_NKINDS"
	print "};"
	print ""
	print "#ifdef TOKEN_TABLE"
	print "static const struct TokInfo tokinfo[T_NKINDS] = {"
	for (i = 1; i <= n; i++)
		if (names[i] in spelling) {
			printf "\t[T_%s] = {%s, %s},\n", names[i], spelling[names[i]], flag[names[i]]
			ns++
		}
	print "};"
	print "#endif"
	printf "%d kinds, %d with spellings\n", n, ns > "/dev/stderr"
}' internal/token/token.go >src/tokens.inc
