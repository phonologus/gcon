#!/bin/sh
# embed.sh: write the files that gcon carries inside itself, as C:
#
#   src/helppages.inc   gcon help's pages, from src/help (NAME.txt is
#                       "gcon help NAME"; gcon.txt is the overview)
#   src/docstyle.inc    the documentation's stylesheet, src/doc/style.css
#   src/docsearch.inc   its search script, src/doc/search.js
#
# Run by build.sh. The output is committed, so that everything that
# compiles src/*.c has it; src/tests/help.sh checks that it is current.
# design/design.md, "Documentation".
#
#   tools/embed.sh [dir]    # write into dir instead of src
#
# A help page for a command starts with its usage, "usage: gcon NAME
# ...", up to the first blank line; that part is what gcon prints when
# the command is misused. A topic's page has no usage. The C stays
# ASCII: other bytes are written as octal escapes.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root/src}

# cstring FILE: FILE's lines as C string literals, one to a line.
cstring() {
	LC_ALL=C awk '
	BEGIN {
		for (i = 128; i < 256; i++)
			oct[sprintf("%c", i)] = sprintf("\\%03o", i)
	}
	{
		s = ""
		for (i = 1; i <= length($0); i++) {
			c = substr($0, i, 1)
			if (c == "\\") c = "\\\\"
			else if (c == "\"") c = "\\\""
			else if (c == "\t") c = "\\t"
			else if (c in oct) c = oct[c]
			s = s c
		}
		printf "\t \"%s\\n\"\n", s
	}' "$1"
}

{
	echo "/* Generated by tools/embed.sh from the pages in src/help: do not edit. */"
	echo
	echo "static const HelpPage helppages[] = {"
	for f in "$root"/src/help/*.txt; do
		printf '\t{"%s",\n' "$(basename "$f" .txt)"
		cstring "$f"
		echo "	},"
	done
	echo "};"
} >"$out/helppages.inc.new"
mv "$out/helppages.inc.new" "$out/helppages.inc"

for pair in docstyle:style.css docsearch:search.js; do
	name=${pair%%:*} file=${pair#*:}
	{
		echo "/* Generated by tools/embed.sh from src/doc/$file: do not edit. */"
		cstring "$root/src/doc/$file"
	} >"$out/$name.inc.new"
	mv "$out/$name.inc.new" "$out/$name.inc"
done
