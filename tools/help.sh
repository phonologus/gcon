#!/bin/sh
# help.sh: write src/helppages.inc, the pages of gcon help, from the
# plain text files in src/help (NAME.txt is "gcon help NAME"; gcon.txt is
# the overview). Run by build.sh. The output is committed, so that
# everything that compiles src/*.c has it; src/tests/help.sh checks that
# it is current.
# design/design.md, "Documentation".
#
# A command's page starts with its usage, "usage: gcon NAME ...", up to
# the first blank line; that part is what gcon prints when the command
# is misused. A topic's page has no usage. The C stays ASCII: other
# bytes are written as octal escapes.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root/src/helppages.inc} # tools/help.sh [file]
tmp=$out.new
{
	echo "/* Generated by tools/help.sh from the pages in src/help: do not edit. */"
	echo
	echo "static const HelpPage helppages[] = {"
	for f in "$root"/src/help/*.txt; do
		name=$(basename "$f" .txt)
		LC_ALL=C awk -v name="$name" '
		BEGIN {
			for (i = 128; i < 256; i++)
				oct[sprintf("%c", i)] = sprintf("\\%03o", i)
			printf "\t{\"%s\",\n", name
		}
		{
			s = ""
			for (i = 1; i <= length($0); i++) {
				c = substr($0, i, 1)
				if (c == "\\") c = "\\\\"
				else if (c == "\"") c = "\\\""
				else if (c == "\t") c = "\\t"
				else if (c in oct) c = oct[c]
				s = s c
			}
			printf "\t \"%s\\n\"\n", s
		}
		END { print "\t}," }' "$f"
	done
	echo "};"
} >"$tmp"
mv "$tmp" "$out"
