#!/bin/sh
# uclass.sh: write lib/gcon/uclass.icn, the uclass module, from the
# Unicode Character Database vendored in deps/unicode, after checking
# its SHA-256s against deps/deps.lock. Run by build.sh; never uses the
# network (deps/update.sh fetches). design/design.md, "Csets and usets".
#
# uclass(name) produces, as a uset, a general category (L, Lu, Nd, ...;
# a one-letter major category is the union of its subcategories) from
# UnicodeData.txt, or a script (Latin, Greek, Han, ...) from Scripts.txt:
# the names of Go's unicode package. Surrogates, which no uset holds,
# are left out (so Cs is empty).
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
deps=$root/deps
sha256() { { sha256sum "$1" 2>/dev/null || shasum -a 256 "$1"; } | awk '{print $1; exit}'; }
grep -v '^#' "$deps/deps.lock" | while read -r name ver sha url; do
	[ "$(sha256 "$deps/unicode/$name")" = "$sha" ] ||
		{ echo "uclass.sh: deps/unicode/$name does not match deps/deps.lock" >&2; exit 1; }
done
ver=$(awk '$1 == "UnicodeData.txt" { print $2 }' "$deps/deps.lock")
out=$root/lib/gcon/uclass.icn
page=$root/doc/ref/uclass.md
if [ "${1:-}" = -o ]; then # tools/uclass.sh -o dir: both files into dir
	out=$2/uclass.icn page=$2/uclass.md
fi
mkdir -p "$(dirname "$out")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# "name lo hi" (decimal) for every category and script range
awk -F';' '
function hex(s,   i, c, v) {
	v = 0
	for (i = 1; i <= length(s); i++) {
		c = index("0123456789ABCDEF", toupper(substr(s, i, 1))) - 1
		v = v * 16 + c
	}
	return v
}
function emit(n, lo, hi) {
	if (hi < 55296 || lo > 57343) { print n, lo, hi; return }
	if (lo >= 55296 && hi <= 57343) { print n, -1, -1; return } # only surrogates: the name, empty
	if (lo < 55296) print n, lo, 55295
	if (hi > 57343) print n, 57344, hi
}
FILENAME ~ /UnicodeData/ {
	cp = hex($1)
	if ($2 ~ /, First>$/) { first = cp; next }
	lo = $2 ~ /, Last>$/ ? first : cp
	emit($3, lo, cp)
	emit(substr($3, 1, 1), lo, cp)
	next
}
{
	sub(/#.*/, "")
	if ($0 ~ /^[ \t]*$/) next
	r = $1; s = $2
	gsub(/[ \t]/, "", r); gsub(/[ \t]/, "", s)
	n = split(r, e, /\.\./)
	emit(s, hex(e[1]), hex(e[n]))
}' "$deps/unicode/UnicodeData.txt" "$deps/unicode/Scripts.txt" |
LC_ALL=C sort -k1,1 -k2,2n >"$tmp/ranges"

# merge each name's ranges, and write a uset literal for it
awk -v ver="$ver" '
# esc is the escape for code point v: \u and 4 hex digits, or \U and 6
function esc(v,   s, w) {
	w = v < 65536 ? 4 : 6
	s = ""
	do { s = substr("0123456789abcdef", v % 16 + 1, 1) s; v = int(v / 16) } while (v > 0 || length(s) < w)
	return (w == 4 ? "\\u" : "\\U") s
}
function add(t) {
	if (col + length(t) > 72) { printf "_\n      "; col = 6 }
	printf "%s", t
	col += length(t)
}
function flush() {
	if (name == "") return
	if (lo < 0) { printf "'"'"'\n"; return }
	add(lo == hi ? esc(lo) : esc(lo) ".." esc(hi))
	printf "'"'"'\n"
}
BEGIN {
	print "############################################################################"
	print "#"
	print "#\tFile:     uclass.icn"
	print "#"
	print "#\tSubject:  Unicode character classes as usets"
	print "#"
	print "############################################################################"
	print "#"
	print "#   uclass(name) produces the uset of the Unicode general category or"
	print "#   script name, as Go'"'"'s unicode package names them: a category of one"
	print "#   letter or two (\"L\", \"Lu\", \"Nd\", \"Zs\", ...; a one-letter major"
	print "#   category is the union of its subcategories) or a script (\"Latin\","
	print "#   \"Greek\", \"Han\", ...). It fails for any other name. Surrogates,"
	print "#   which no uset holds, are left out, so \"Cs\" is empty."
	print "#"
	print "#   Generated by gcon'"'"'s tools/uclass.sh from the Unicode Character"
	print "#   Database " ver " (UnicodeData.txt, Scripts.txt); do not edit."
	print "#   The data is from Unicode, Inc., under the Unicode License v3: see"
	print "#   deps/unicode/LICENSE in gcon."
	print "#"
	print "############################################################################"
	print ""
	print "procedure uclass(name) #: Unicode character class as a uset"
	print "   static classes"
	print "   initial classes := uclass_table()"
	print "   return \\classes[name]"
	print "end"
	print ""
	print "procedure uclass_table()"
	print "   local t"
	print "   t := table()"
}
$1 != name {
	flush()
	name = $1; lo = $2; hi = $3
	printf "   t[\"%s\"] := u'"'"'", name
	col = 10 + length(name)
	next
}
$2 < 0 { next }
lo < 0 { lo = $2; hi = $3; next }
$2 <= hi + 1 { if ($3 > hi) hi = $3; next }
{ add(lo == hi ? esc(lo) : esc(lo) ".." esc(hi)); lo = $2; hi = $3 }
END {
	flush()
	print "   return t"
	print "end"
}' "$tmp/ranges" >"$tmp/uclass.icn"
mv "$tmp/uclass.icn" "$out"

# doc/ref/uclass.md, the reference's page of the classes (committed;
# src/tests/doc.sh checks that it is current): each class with the
# number of characters in it, and examples whose output comes from the
# same data, so that gcon doc -test checks the page against the module.
awk -v ver="$ver" '
function cat(c) {
	return c == "L" ? "letters" : c == "Lu" ? "uppercase letters" : c == "Ll" ? "lowercase letters" : \
		c == "Lt" ? "titlecase letters" : c == "Lm" ? "modifier letters" : c == "Lo" ? "other letters" : \
		c == "M" ? "marks" : c == "Mn" ? "nonspacing marks" : c == "Mc" ? "spacing marks" : \
		c == "Me" ? "enclosing marks" : c == "N" ? "numbers" : c == "Nd" ? "decimal digits" : \
		c == "Nl" ? "letter numbers" : c == "No" ? "other numbers" : c == "P" ? "punctuation" : \
		c == "Pc" ? "connector punctuation" : c == "Pd" ? "dashes" : c == "Ps" ? "opening punctuation" : \
		c == "Pe" ? "closing punctuation" : c == "Pi" ? "initial quotes" : c == "Pf" ? "final quotes" : \
		c == "Po" ? "other punctuation" : c == "S" ? "symbols" : c == "Sm" ? "mathematical symbols" : \
		c == "Sc" ? "currency symbols" : c == "Sk" ? "modifier symbols" : c == "So" ? "other symbols" : \
		c == "Z" ? "separators" : c == "Zs" ? "spaces" : c == "Zl" ? "the line separator" : \
		c == "Zp" ? "the paragraph separator" : c == "C" ? "other: control, format, private use" : \
		c == "Cc" ? "control characters" : c == "Cf" ? "format characters" : \
		c == "Cs" ? "surrogates (none in a uset)" : c == "Co" ? "private use" : "?"
}
$2 >= 0 { n[$1] += $3 - $2 + 1 }
{ if (!($1 in seen)) { seen[$1] = 1; names[++nn] = $1 }; if (!($1 in n)) n[$1] = 0 }
END {
	print "# Unicode character classes"
	print ""
	print "The general categories and scripts of the Unicode Character Database"
	print "(Unicode " ver "), as usets: `link uclass`, then `uclass(name)`. The"
	print "module is Gcon'"'"'s own (`lib/gcon`, searched after the IPL), generated"
	print "from the database when Gcon is built; this page is generated with it."
	print "The names are those of Go'"'"'s `unicode` package."
	print ""
	print "## uclass"
	print ""
	print "```"
	print "uclass(s)"
	print "```"
	print ""
	print "Produces the uset of the general category or script `s`: a category"
	print "of two letters (`\"Lu\"`), a major category of one, the union of its"
	print "subcategories (`\"L\"`), or a script (`\"Greek\"`). Fails for any other"
	print "name. Surrogates, which no uset holds, are left out, so `\"Cs\"` is"
	print "empty. With a uset, the scanning functions step over whole UTF-8"
	print "characters, so `uclass` classifies the characters of UTF-8 text."
	print ""
	print "```icon"
	print "link uclass"
	print ""
	print "procedure main()"
	print "   \"Ωμέγα, 42 €\" ? while tab(upto(uclass(\"L\"))) do"
	print "      write(tab(many(uclass(\"L\"))))"
	print "   write(*uclass(\"Nd\"), \" \", *uclass(\"Greek\"))"
	print "   write(uclass(\"Klingon\") | \"no such class\")"
	print "end"
	print "```"
	print ""
	print "Output:"
	print ""
	print "```"
	print "Ωμέγα"
	print n["Nd"] " " n["Greek"]
	print "no such class"
	print "```"
	print ""
	print "**See also:** [uset](unicode.md#uset), [many](scanning.md#many),"
	print "[upto](scanning.md#upto)."
	print ""
	print "## General categories"
	print ""
	print "| Name | Characters | Count |"
	print "|---|---|---:|"
	split("L Lu Ll Lt Lm Lo M Mn Mc Me N Nd Nl No P Pc Pd Ps Pe Pi Pf Po S Sm Sc Sk So Z Zs Zl Zp C Cc Cf Cs Co", order, " ")
	for (i = 1; i in order; i++) {
		iscat[order[i]] = 1
		if (order[i] in seen)
			printf "| `%s` | %s | %d |\n", order[i], cat(order[i]), n[order[i]]
	}
	print ""
	print "## Unicode scripts"
	print ""
	print "| Name | Count |"
	print "|---|---:|"
	for (i = 1; i <= nn; i++)
		if (!(names[i] in iscat))
			printf "| `%s` | %d |\n", names[i], n[names[i]]
}' "$tmp/ranges" >"$tmp/uclass.md"
mv "$tmp/uclass.md" "$page"
echo "built lib/gcon/uclass.icn and doc/ref/uclass.md (Unicode $ver)"
