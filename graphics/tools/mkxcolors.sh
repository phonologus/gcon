#!/bin/sh
# Generate src/xcolors.c, X's colour-name database, from X.Org's
# rgb.txt (tools/rgb.txt, from the test VM's x11-common package) and
# its licence (tools/rgb-COPYING).
#
#     sh tools/mkxcolors.sh > src/xcolors.c
set -eu
here=$(cd "$(dirname "$0")" && pwd)
echo "/*"
echo " * xcolors.c -- X's colour names, for nativecolor(): GENERATED by"
echo " * tools/mkxcolors.sh from X.Org's rgb.txt; do not edit."
echo " *"
echo " * The colour names and values are X.Org's (app/rgb), under this licence:"
echo " *"
# the licence, without trailing blank lines, each line " * " (trimmed)
awk '{ l[NR] = $0 } NF { last = NR } END { for (i = 1; i <= last; i++) { s = " * " l[i]; sub(/[ \t]+$/, "", s); print s } }' \
	"$here/rgb-COPYING"
echo " */"
echo "#include <string.h>"
echo "#include <strings.h>"
echo "#include \"sdlgfx.h\""
echo
echo "static const struct { const char *name; unsigned char r, g, b; } xc[] = {"
# "r g b name": the name (lower-cased; it may hold spaces) is what
# follows the third number; the first definition of a name wins
awk '/^!/ || NF == 0 { next }
{
	name = $0
	sub(/^[ \t]*[^ \t]+[ \t]+[^ \t]+[ \t]+[^ \t]+[ \t]*/, "", name)
	sub(/[ \t]+$/, "", name)
	key = tolower(name)
	if (key in seen) next
	seen[key] = 1
	printf "%s\t%d\t%d\t%d\n", key, $1, $2, $3
}' "$here/rgb.txt" | LC_ALL=C sort -t '	' -k1,1 |
	awk -F '	' '{ printf "   {\"%s\", %d, %d, %d},\n", $1, $2, $3, $4 }'
cat <<'C'
};

/* Look up an X colour name (case-insensitively, as the X server does);
 * returns 1 and the 8-bit device values, or 0. */
int xcolor_lookup(const char *name, int *r, int *g, int *b)
{
   int lo = 0, hi = (int)(sizeof xc / sizeof xc[0]) - 1;
   while (lo <= hi) {
      int mid = (lo + hi) / 2, c = strcasecmp(name, xc[mid].name);
      if (c == 0) {
         *r = xc[mid].r; *g = xc[mid].g; *b = xc[mid].b;
         return 1;
      }
      if (c < 0) hi = mid - 1; else lo = mid + 1;
   }
   return 0;
}
C
