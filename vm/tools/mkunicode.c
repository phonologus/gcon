/*
 * mkunicode VERSION <UnicodeData.txt >unicode.c: gcon-vm's Unicode
 * table, from the Unicode Character Database. gen_nonprint lists, as
 * sorted inclusive ranges, the code points from U+0080 up that are not
 * printable (isprint_rune in src/util.c handles ASCII itself).
 * Printable is Go's definition (strconv.IsPrint, which gcon followed
 * first): letters, marks, numbers, punctuation and symbols (general
 * categories L, M, N, P, S), and the ASCII space; so not controls,
 * format characters, surrogates, private use, unassigned code points,
 * or spaces and separators other than U+0020.
 *
 * Run by tools/mkunicode.sh; never needed to build.
 */
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

enum { MaxRune = 0x10FFFF };

static bool printable[MaxRune + 1];

static void die(const char *msg, long line) {
	fprintf(stderr, "mkunicode: line %ld: %s\n", line, msg);
	exit(1);
}

int main(int argc, char **argv) {
	if (argc != 2) {
		fprintf(stderr, "usage: mkunicode VERSION <UnicodeData.txt >unicode.c\n");
		return 2;
	}
	char line[1024];
	long n = 0, first = -1;
	while (fgets(line, sizeof line, stdin)) {
		n++;
		if (!strchr(line, '\n') && !feof(stdin))
			die("line too long", n);
		/* code;name;category;... */
		char *name = strchr(line, ';');
		char *cat = name ? strchr(name + 1, ';') : NULL;
		if (!cat)
			die("malformed", n);
		*name++ = 0;
		*cat++ = 0;
		char *end;
		long cp = strtol(line, &end, 16);
		if (end == line || *end || cp < 0 || cp > MaxRune)
			die("bad code point", n);
		bool p = strchr("LMNPS", cat[0]) != NULL && cat[0] != 0;
		size_t nl = strlen(name);
		if (nl > 8 && !strcmp(name + nl - 8, ", First>")) {
			first = cp;
			continue;
		}
		long lo = cp;
		if (nl > 7 && !strcmp(name + nl - 7, ", Last>")) {
			if (first < 0 || first > cp)
				die("range Last without First", n);
			lo = first;
		} else if (first >= 0)
			die("range First without Last", n);
		first = -1;
		for (long c = lo; c <= cp; c++)
			printable[c] = p;
	}
	if (first >= 0)
		die("range First without Last at end", n);
	printable[' '] = true;

	printf("/* Generated by tools/mkunicode.sh from Unicode %s; do not edit. */\n\n", argv[1]);
	printf("#include \"gcon-vm.h\"\n\n");
	printf("const uint32_t gen_nonprint[][2] = {\n");
	int count = 0;
	for (long c = 0x80; c <= MaxRune;) {
		if (printable[c]) {
			c++;
			continue;
		}
		long lo = c;
		while (c <= MaxRune && !printable[c])
			c++;
		printf("\t{0x%lX, 0x%lX},\n", lo, c - 1);
		count++;
	}
	printf("};\n");
	printf("const int gen_nnonprint = %d;\n", count);
	return 0;
}
