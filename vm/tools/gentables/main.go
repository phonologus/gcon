// Command gentables writes src/gen_tables.c: the names of gcon's
// builtins, which a built program refers to (gcon's
// internal/vm/builtinref.go), and the code points that are not
// printable (strconv.IsPrint), which images escape. It is part of
// gcon's module, so it reads gcon's internal/vm directly: see
// gentables.sh.
package main

import (
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/phonologus/gcon/internal/vm"
)

func names[T any](m map[string]T) []string {
	s := make([]string, 0, len(m))
	for k := range m {
		s = append(s, k)
	}
	sort.Strings(s)
	return s
}

func main() {
	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by tools/gentables.sh from gcon %s; do not edit. */\n", os.Args[1])
	fmt.Fprintf(&b, "/* Unicode %s (Go's strconv.IsPrint). */\n\n", unicode.Version)
	b.WriteString("#include \"gcon-vm.h\"\n\n")
	for _, t := range []struct {
		name string
		s    []string
	}{{"ops", names(vm.Ops)}, {"functions", names(vm.Functions)}} {
		fmt.Fprintf(&b, "const char *const gen_%s[] = {\n", t.name)
		for _, n := range t.s {
			fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(n))
		}
		fmt.Fprintf(&b, "};\nconst int gen_n%s = %d;\n\n", t.name, len(t.s))
	}
	// Ranges of code points from 0x80 that are not printable.
	b.WriteString("const uint32_t gen_nonprint[][2] = {\n")
	n := 0
	for r := rune(0x80); r <= utf8.MaxRune; r++ {
		if strconv.IsPrint(r) {
			continue
		}
		lo := r
		for r+1 <= utf8.MaxRune && !strconv.IsPrint(r+1) {
			r++
		}
		fmt.Fprintf(&b, "\t{0x%X, 0x%X},\n", lo, r)
		n++
	}
	fmt.Fprintf(&b, "};\nconst int gen_nnonprint = %d;\n", n)
	os.Stdout.WriteString(b.String())
}
